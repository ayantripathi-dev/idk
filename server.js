// 4. Asset & Thumbnail Prompter (ForgeGUI inspired)
app.post('/api/generate-asset-prompt', (req, res) => {
  const { assetType, style, description } = req.body;
  if (!description) {
    return res.status(400).json({ error: 'Description is required' });
  }

  const type = assetType || 'Roblox Thumbnail';
  const assetStyle = style || 'Vibrant 3D Render';

  const optimizedPrompt = `High quality ${type}, ${assetStyle} style. ${description}, professional lighting, octave render, Unreal Engine 5 aesthetic, Roblox game asset art, highly detailed, 8k resolution`;
  const negativePrompt = `blurry, low quality, distorted geometry, grainy, bad composition, watermark`;

  res.json({
    success: true,
    assetType: type,
    style: assetStyle,
    optimizedPrompt,
    negativePrompt,
    recommendedAspectRatio: type.includes('Thumbnail') ? '16:9' : '1:1'
  });
});

// 5. Saved Projects Management
app.get('/api/projects', (req, res) => {
  res.json({ projects: savedProjects });
});

app.post('/api/projects', (req, res) => {
  const { name, type, content } = req.body;
  if (!name || !content) {
    return res.status(400).json({ error: 'Name and content are required' });
  }

  const newProject = {
    id: 'proj_' + Date.now(),
    name,
    type: type || 'Script',
    content,
    createdAt: new Date().toISOString()
  };

  savedProjects.push(newProject);
  res.status(201).json({ success: true, project: newProject });
});

// Start Server
if (require.main === module) {
  app.listen(PORT, () => {
    console.log(`AI Game Studio running on http://localhost:${PORT}`);
  });
}

module.exports = app;
