const express = require('express');
const path = require('path');

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());
app.use(express.static(path.join(__dirname, 'public')));

// In-memory store for settings and projects
let llmConfig = {
  baseUrl: process.env.MODEL_BASE_URL || 'https://api.openai.com/v1',
  apiKey: process.env.MODEL_API_KEY || '',
  modelName: 'gpt-4o'
};

let savedProjects = [];

// API Endpoints

// 1. LLM Model Settings
app.get('/api/config', (req, res) => {
  res.json({
    baseUrl: llmConfig.baseUrl,
    modelName: llmConfig.modelName,
    hasApiKey: Boolean(llmConfig.apiKey)
  });
});

app.post('/api/config', (req, res) => {
  const { baseUrl, apiKey, modelName } = req.body;
  if (baseUrl !== undefined) llmConfig.baseUrl = baseUrl;
  if (apiKey !== undefined) llmConfig.apiKey = apiKey;
  if (modelName !== undefined) llmConfig.modelName = modelName;

  res.json({
    success: true,
    message: 'Configuration updated successfully',
    config: {
      baseUrl: llmConfig.baseUrl,
      modelName: llmConfig.modelName,
      hasApiKey: Boolean(llmConfig.apiKey)
    }
  });
});

// 2. Luau AI Script Assistant (Lemonade & ForgeGUI inspired)
app.post('/api/generate-script', (req, res) => {
  const { prompt, scriptType } = req.body;
  if (!prompt) {
    return res.status(400).json({ error: 'Prompt is required' });
  }

  const type = scriptType || 'ServerScript';
  const timestamp = new Date().toISOString();

  // Template generators based on prompt keywords
  let generatedCode = '';
  let explanation = '';

  if (prompt.toLowerCase().includes('inventory')) {
    generatedCode = `-- Luau Inventory System (${type})
-- Generated by AI Game Studio
local Players = game:GetService("Players")
local ReplicatedStorage = game:GetService("ReplicatedStorage")

local InventoryData = {}

local function setupInventory(player)
    InventoryData[player.UserId] = {
        Coins = 100,
        Items = {"Starter Sword", "Health Potion"}
    }
    print("Inventory initialized for " .. player.Name)
end

Players.PlayerAdded:Connect(setupInventory)
`;
    explanation = 'Generates a robust player inventory system template with item storage and player setup handlers.';
  } else if (prompt.toLowerCase().includes('leaderboard') || prompt.toLowerCase().includes('leaderstats')) {
    generatedCode = `-- Luau Leaderstats System (${type})
-- Generated by AI Game Studio
local Players = game:GetService("Players")

local function onPlayerAdded(player)
    local leaderstats = Instance.new("Folder")
    leaderstats.Name = "leaderstats"
    leaderstats.Parent = player

    local coins = Instance.new("IntValue")
    coins.Name = "Coins"
    coins.Value = 0
    coins.Parent = leaderstats

    local level = Instance.new("IntValue")
    level.Name = "Level"
    level.Value = 1
    level.Parent = leaderstats
end

Players.PlayerAdded:Connect(onPlayerAdded)
`;
    explanation = 'Creates standard Roblox leaderstats with Coins and Level trackers.';
  } else {
    generatedCode = `-- Luau Custom Feature Script (${type})
-- Prompt: ${prompt}
-- Generated at: ${timestamp}

local ReplicatedStorage = game:GetService("ReplicatedStorage")
local TweenService = game:GetService("TweenService")

print("Initializing AI Generated Module: ${prompt.replace(/\n/g, ' ')}")

local function executeFeature(player)
    -- Custom logic for: ${prompt}
    return true
end

return {
    Execute = executeFeature
}
`;
    explanation = `Generated custom Luau module for feature: "${prompt}".`;
  }

  res.json({
    success: true,
    prompt,
    scriptType: type,
    code: generatedCode,
    explanation,
    modelUsed: llmConfig.modelName
  });
});

